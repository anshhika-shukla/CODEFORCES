

import java.util.*;
public class codeforces11  //Problem 2210, A Simple Sequencea
{
    public static void main(String args[])
    {
        Scanner sc=new Scanner(System.in);
        int t=sc.nextInt();
        while(t-->0)
        {
            int n=sc.nextInt();
            for(int i=n;i>=1;i--)
            {
                System.out.print(i+" ");
            }
        }
    }
}
