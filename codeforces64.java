import java.util.*;
public class codeforces64    //Problem 1371,A. Magical Sticks
{
    public static void main(String args[]) 
    {
        Scanner sc = new Scanner(System.in);
        int t = sc.nextInt();
        while (t-- > 0)
        {
            long n = sc.nextLong();
            System.out.println((n + 1) / 2);
        }
    }
}
